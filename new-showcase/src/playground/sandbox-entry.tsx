/*
 * Standalone entry for the playground preview SANDBOX. This bundle is loaded into an
 * `<iframe sandbox="allow-scripts">` (an opaque origin), so user-supplied code runs here — isolated
 * from the showcase origin's cookies, storage and DOM — instead of being `new Function`-evaluated in
 * the main page. Code arrives ONLY via postMessage from the embedding playground; there is no
 * URL/query-string code transport, so no shareable link can carry code into this document.
 */

// Self-contained widgets-core base styles with every font inlined as a data: URI. This REPLACES the
// package's basic.css import — the sandbox's opaque origin would block its url()-based cross-origin
// @font-face fetches. Generated by `gen:sandbox-fonts` (runs automatically before dev/build).
import "../generated/sandbox-fonts.css";

import type { ComponentType, ReactElement, ReactNode } from "react";
import { Component, createElement, StrictMode, useCallback, useEffect, useMemo, useRef, useState } from "react";
import { createRoot } from "react-dom/client";
import { css, styled, StyleSheetManager, ThemeProvider } from "styled-components";

import {
	GlobalStyles,
	noop,
	ProgressIndicator,
	shouldForwardProp,
	WidgetsRoot
} from "@com.mgmtp.a12.widgets/widgets-core";

import type * as LiveEvalModule from "../helpers/live-eval.js";
import { ShowcaseStyles } from "../helpers/showcase-styles.js";
import { ThemeContext } from "../helpers/theme-selector.js";

import type { SandboxRunMessage } from "./playground-utils.js";
import {
	DEFAULT_PLAYGROUND_THEME,
	getPlaygroundTheme,
	SANDBOX_REPLY_SOURCE,
	SANDBOX_REQUEST_SOURCE
} from "./playground-utils.js";

const isEmbedded = window.parent !== window.self;

interface ErrorBoundaryProps {
	children: ReactNode;
	onError: (error: Error) => void;
}

interface ErrorBoundaryState {
	hasError: boolean;
}

class ErrorBoundary extends Component<ErrorBoundaryProps, ErrorBoundaryState> {
	state: ErrorBoundaryState = { hasError: false };

	static getDerivedStateFromError(): ErrorBoundaryState {
		return { hasError: true };
	}

	componentDidCatch(error: Error): void {
		this.props.onError(error);
	}

	componentDidUpdate(prevProps: ErrorBoundaryProps): void {
		if (prevProps.children !== this.props.children) {
			this.setState({ hasError: false });
		}
	}

	render(): ReactNode {
		if (this.state.hasError) {
			return null;
		}

		return this.props.children;
	}
}

const StyledPreview = styled.div<{ $darkBackground?: boolean }>(({ theme, $darkBackground }) => {
	const { colors, spacing } = theme;

	return css`
		align-items: center;
		background-color: ${$darkBackground ? "#dbdfe8" : colors.background.secondaryBackground};
		box-sizing: border-box;
		display: flex;
		flex: 1;
		justify-content: center;
		min-height: 100vh;
		overflow: auto;
		padding: ${spacing.spacing.spacingXl}px;
		position: relative;

		/*
		 * Use the data-role selector instead of StyledShowcaseExampleWrapper here.
		 * Some examples load ShowcaseExampleContent from playground-sources.json, so the styled-component selector changes.
		 */
		&:has([data-role="section-content"]) {
			> div {
				width: 100%;
			}
			[data-role="section-content"] {
				border: 1px solid #dbdfe8;
			}
		}
	`;
});

const StyledError = styled.div`
	&:not(:empty) {
		background: #ff5555;
		bottom: 0;
		color: white;
		font-family: monospace;
		font-size: 12px;
		left: 0;
		max-height: 150px;
		overflow: auto;
		padding: 8px 12px;
		position: fixed;
		right: 0;
		white-space: pre-wrap;
	}
`;

function SandboxApp(): ReactElement {
	const currentCodeRef = useRef<string | null>(null);
	const liveEvalRef = useRef<Promise<typeof LiveEvalModule> | null>(null);
	const [themeName, setThemeName] = useState(DEFAULT_PLAYGROUND_THEME);
	const [darkBackground, setDarkBackground] = useState(false);
	const [element, setElement] = useState<ComponentType | null>(null);
	const [error, setError] = useState<string | null>(null);
	const [isLoading, setIsLoading] = useState(false);
	const theme = useMemo(() => getPlaygroundTheme(themeName), [themeName]);

	const runCode = useCallback(async (data: SandboxRunMessage): Promise<void> => {
		setThemeName(data.themeName);
		setDarkBackground(!!data.darkBackground);

		if (data.code === currentCodeRef.current) {
			return;
		}

		currentCodeRef.current = data.code;
		setError(null);
		setIsLoading(true);

		try {
			if (!liveEvalRef.current) {
				liveEvalRef.current = import("../helpers/live-eval.js");
			}

			const { evaluateCode, preloadCodeDependencies } = await liveEvalRef.current;

			await preloadCodeDependencies(data.code, data.sourceName);

			const result = evaluateCode(data.code, data.sourceName);
			setElement(() => result.element);
			setError(result.error);
		} catch (err) {
			setElement(null);
			currentCodeRef.current = null;
			liveEvalRef.current = null;
			setError(err instanceof Error ? err.message : String(err));
		} finally {
			setIsLoading(false);
		}
	}, []);

	useEffect(() => {
		function handleMessage(event: MessageEvent<SandboxRunMessage | undefined>): void {
			const { data } = event;

			if (data && data.source === SANDBOX_REQUEST_SOURCE && data.type === "run") {
				void runCode(data);
			}
		}

		window.addEventListener("message", handleMessage);

		// Tell the embedding playground we are mounted and listening, so it sends the current code.
		if (isEmbedded) {
			window.parent.postMessage({ source: SANDBOX_REPLY_SOURCE, type: "ready" }, "*");
		}

		return () => window.removeEventListener("message", handleMessage);
	}, [runCode]);

	const handleRuntimeError = useCallback((err: Error) => setError(err.message), []);

	return (
		<StyleSheetManager shouldForwardProp={shouldForwardProp}>
			<ThemeProvider theme={theme}>
				<ThemeContext.Provider value={{ theme: themeName, setTheme: noop }}>
					<GlobalStyles />
					<ShowcaseStyles />
					<WidgetsRoot>
						<StyledPreview $darkBackground={darkBackground} aria-busy={isLoading}>
							<ErrorBoundary onError={handleRuntimeError}>{element ? createElement(element) : null}</ErrorBoundary>
							{isLoading && (
								<ProgressIndicator
									id="sandbox-loading-preview"
									label="Loading preview"
									size="medium"
									fastAppear
									outerOverlayVariant="transparent"
								/>
							)}
						</StyledPreview>
						<StyledError>{error}</StyledError>
					</WidgetsRoot>
				</ThemeContext.Provider>
			</ThemeProvider>
		</StyleSheetManager>
	);
}

const container = document.getElementById("root");

createRoot(container!).render(
	<StrictMode>
		<SandboxApp />
	</StrictMode>
);
