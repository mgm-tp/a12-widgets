import type monaco from "monaco-editor";
import type { ComponentType, ReactElement } from "react";
import { lazy, Suspense, useCallback } from "react";
import { styled } from "styled-components";

// Bundled .d.ts for the other packages the playground exposes — react, csstype, styled-components (plus
// shims for their leaf externals). Generated by `gen:editor-types` into a [{ path, content }] manifest;
// mounting these at their virtual node_modules paths lets Monaco resolve `import ... from "react" |
// "styled-components"` and type-check the snippet. Imported raw so it stays in the lazy editor chunk.
import editorTypesManifest from "../generated/editor-types.json?raw";
// Rolled-up widgets-core type declarations (generated by `pnpm gen:widgets-core-types`). Fed to Monaco
// so the editor offers real autocomplete for the widgets API. Imported as raw text (kept in the lazy
// editor chunk, never the main bundle).
import widgetsCoreTypes from "../generated/widgets-core.d.ts.txt?raw";

interface EditorTypeEntry {
	path: string;
	content: string;
}

function parseEditorTypes(): EditorTypeEntry[] {
	try {
		return JSON.parse(editorTypesManifest) as EditorTypeEntry[];
	} catch {
		return [];
	}
}

const editorTypes = parseEditorTypes();

// Self-host Monaco's language workers instead of letting @monaco-editor/react pull `monaco` from the
// jsdelivr CDN (its default). The CDN path makes Monaco spawn the TypeScript worker — which powers all
// IntelliSense — through a cross-origin `blob:` worker. That breaks the moment a deployment adds a
// strict CSP (`worker-src blob:` blocked) or restricts egress to the CDN: the editor still renders and
// highlights, but IntelliSense silently dies. Bundling the workers keeps everything same-origin, so
// autocomplete works identically in dev, `serve`, and every deployed environment.
function configureMonacoWorkers(): void {
	(
		self as unknown as { MonacoEnvironment?: { getWorker(workerId: string, label: string): Worker } }
	).MonacoEnvironment = {
		getWorker(_workerId: string, label: string): Worker {
			if (label === "typescript" || label === "javascript") {
				return new Worker(new URL("monaco-editor/language/typescript/ts.worker.js", import.meta.url));
			}

			return new Worker(new URL("monaco-editor/editor/editor.worker.js", import.meta.url));
		}
	};
}

// Monaco (@monaco-editor/react + monaco-editor) is multi-MB. Loading both lazily — and pointing
// @monaco-editor/react at the bundled `monaco` via loader.config — keeps the editor and its workers out
// of the main bundle and off the CDN. Fetched only when the user actually opens an editor (live mode or
// playground). @monaco-editor/react returns React 18 Element types, incompatible with React 19's ReactNode.
const MonacoEditor = lazy(async () => {
	const [reactMonaco, monacoInstance] = await Promise.all([import("@monaco-editor/react"), import("monaco-editor")]);

	configureMonacoWorkers();
	// Use the bundled monaco instance rather than @monaco-editor/react's default CDN download.
	reactMonaco.loader.config({ monaco: monacoInstance });

	return { default: reactMonaco.default as unknown as ComponentType<Record<string, unknown>> };
});

const StyledEditorFallback = styled.div`
	align-items: center;
	color: #888;
	display: flex;
	font-family: monospace;
	font-size: 13px;
	height: 100%;
	justify-content: center;
	min-height: 120px;
	width: 100%;
`;

/**
 * Lazy-loaded Monaco editor. Props are forwarded verbatim to `@monaco-editor/react`'s default export.
 */
export function LazyMonacoEditor(props: Record<string, unknown>): ReactElement {
	return (
		<Suspense fallback={<StyledEditorFallback>Loading editor…</StyledEditorFallback>}>
			<MonacoEditor {...props} />
		</Suspense>
	);
}

/**
 * `beforeMount` handler that configures Monaco's TypeScript language service for the live snippets
 * (React JSX, lenient diagnostics). Lives here — next to the editor — so consumers can configure the
 * editor without importing the (heavier) code-evaluation module.
 */
export function useEditorBeforeMount(): (instance: typeof monaco) => void {
	return useCallback((instance: typeof monaco) => {
		const { typescriptDefaults, JsxEmit, ScriptTarget, ModuleResolutionKind, ModuleKind } = instance.typescript;

		// Syntax validation is on (real parse errors help); semantic validation stays OFF. We ship types for
		// widgets-core + react + styled-components purely to power autocomplete/hover — enabling full type
		// checking surfaces spurious errors on valid snippets (Monaco's worker doesn't resolve React 19's
		// automatic-JSX namespace from the virtual @types graph), which is worse than no checking in a
		// throwaway playground. So: rich IntelliSense, no red squiggles on correct code.
		typescriptDefaults.setDiagnosticsOptions({
			noSemanticValidation: true,
			noSyntaxValidation: false
		});
		typescriptDefaults.setCompilerOptions({
			// Automatic JSX runtime (react/jsx-runtime): snippets use JSX WITHOUT importing the React
			// default, so the classic runtime's "Cannot find name 'React'" error must not fire. (The sandbox
			// still transpiles with the classic runtime via sucrase; this only governs editor diagnostics.)
			jsx: JsxEmit.ReactJSX,
			allowNonTsExtensions: true,
			allowJs: true,
			esModuleInterop: true,
			skipLibCheck: true,
			target: ScriptTarget.Latest,
			module: ModuleKind.ESNext,
			moduleResolution: ModuleResolutionKind.NodeJs,
			baseUrl: "file:///"
		});
		// Mount the widgets-core rollup at its virtual node_modules path so `import { Button } from
		// "@com.mgmtp.a12.widgets/widgets-core"` resolves and autocompletes.
		typescriptDefaults.addExtraLib(
			widgetsCoreTypes,
			"file:///node_modules/@com.mgmtp.a12.widgets/widgets-core/index.d.ts"
		);

		// Mount the react / styled-components / csstype declarations at their virtual node_modules paths.
		for (const { path, content } of editorTypes) {
			typescriptDefaults.addExtraLib(content, path);
		}
	}, []);
}
