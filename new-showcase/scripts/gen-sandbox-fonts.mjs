/*
 * Generates a self-contained stylesheet for the playground preview sandbox, with every font inlined
 * as a base64 data: URI.
 *
 * The preview runs in an opaque-origin sandbox iframe (so untrusted ?code= can't touch the showcase
 * origin). That makes every @font-face fetch cross-origin — which browsers block for fonts unless the
 * host sends CORS headers. Inlining removes the cross-origin fetch entirely, so the preview renders
 * correctly in dev and on any deployment with no host-header dependency.
 *
 * It takes widgets-core's basic.css (the source of truth for the icon + Open Sans faces and the icon
 * CSS classes), rewrites each @font-face to a data URI, and prepends the Roboto faces (which live in
 * the showcase, not basic.css). sandbox-entry imports ONLY this file — never the original basic.css —
 * so no url()-based @font-face remains.
 *
 * The large `Material Symbols Rounded` face (~516 KB) is dropped: the A12 base theme used by the
 * preview renders outlined icons, so rounded is never requested. Re-include it here if that changes.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROBOTO_DIR = resolve(SCRIPT_DIR, "../src/fonts/roboto");
const OUTPUT = resolve(SCRIPT_DIR, "../src/generated/sandbox-fonts.css");

// Font file basenames to skip inlining (left out entirely; the family then falls back).
const SKIP = new Set(["material-symbols-rounded.woff2", "material-symbols-rounded.woff"]);

const MIME = { woff2: "font/woff2", woff: "font/woff" };

function dataUri(path) {
	const ext = path.endsWith(".woff2") ? "woff2" : "woff";

	return `data:${MIME[ext]};base64,${readFileSync(path).toString("base64")}`;
}

/**
 * Rewrites a single @font-face block from basic.css: picks one source (woff2 preferred), inlines it,
 * and replaces the whole `src:` declaration. Returns "" to drop the block (skipped font).
 */
function inlineFontFace(block, baseDir) {
	const sources = [...block.matchAll(/url\("([^"]+)"\)\s*format\("([^"]+)"\)/g)].map((m) => ({
		path: m[1],
		format: m[2]
	}));
	const chosen = sources.find((s) => s.format === "woff2") ?? sources[0];

	if (!chosen) {
		return block;
	}

	if (SKIP.has(basename(chosen.path))) {
		return "";
	}

	const uri = dataUri(resolve(baseDir, chosen.path));

	return block.replace(/src:\s*[^;]*;/, `src: url("${uri}") format("${chosen.format}");`);
}

function robotoFace(file, weight) {
	const uri = dataUri(resolve(ROBOTO_DIR, file));

	return `@font-face {\n\tfont-family: "Roboto";\n\tfont-style: normal;\n\tfont-weight: ${weight};\n\tfont-display: swap;\n\tsrc: url("${uri}") format("woff2");\n}`;
}

const basicCssPath = require.resolve("@com.mgmtp.a12.widgets/widgets-core/styles/basic.css");
const basicCssDir = dirname(basicCssPath);
const basicCss = readFileSync(basicCssPath, "utf8").replace(/@font-face\s*\{[^}]*\}/g, (block) =>
	inlineFontFace(block, basicCssDir)
);

const roboto = [
	robotoFace("Roboto-Light.woff2", 300),
	robotoFace("Roboto-Regular.woff2", 400),
	robotoFace("Roboto-Medium.woff2", 500),
	robotoFace("Roboto-Bold.woff2", 700)
].join("\n\n");

const css = `/* GENERATED by scripts/gen-sandbox-fonts.mjs — do not edit. */\n\n${roboto}\n\n${basicCss}`;

mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, css);

console.log(`Wrote inlined sandbox fonts to ${OUTPUT} (${(css.length / 1024).toFixed(0)} KB).`);
