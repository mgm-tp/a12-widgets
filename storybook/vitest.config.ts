import path from "node:path";
import { fileURLToPath } from "node:url";

import { storybookTest } from "@storybook/addon-vitest/vitest-plugin";
import react from "@vitejs/plugin-react";
import { playwright } from "@vitest/browser-playwright";
import { defineConfig } from "vitest/config";

const dirname = path.dirname(fileURLToPath(import.meta.url));

// Runs every story as a Vitest browser test via @storybook/addon-vitest. Driven
// from the Storybook UI (testing widget) or with `pnpm -F widgets-storybook test:stories`.
export default defineConfig({
	define: {
		// Enable styled-components speedy mode (CSSOM injection), same as vite.config.ts
		SC_DISABLE_SPEEDY: false
	},
	plugins: [react(), storybookTest({ configDir: path.join(dirname, ".storybook") })],
	test: {
		name: "storybook",
		browser: {
			enabled: true,
			headless: true,
			provider: playwright(),
			instances: [{ browser: "chromium" }]
		}
	}
});
